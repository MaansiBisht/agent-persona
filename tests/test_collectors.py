def test_collect_transcript_returns_user_messages_and_tool_signals(tmp_path: Path) -> None:
    """collect_transcript() extracts user text and file paths from a valid JSONL."""
    transcript = tmp_path / "session.jsonl"
    _write_jsonl(
        transcript,
        [
            _user_text_record("I prefer root-cause analysis"),
            _tool_use_record("Read", file_path="/src/main.py"),
        ],
    )
    state_store = tmp_path / "state"

    user_msgs, tool_signals = collect_transcript(transcript, state_store)

    assert "I prefer root-cause analysis" in user_msgs
    assert "/src/main.py" in tool_signals


