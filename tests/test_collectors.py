def _recent_ts() -> str:
    return (datetime.now(timezone.utc) - timedelta(days=1)).isoformat()


def _old_ts() -> str:
    return (datetime.now(timezone.utc) - timedelta(days=100)).isoformat()


def test_collect_file_signals_counts_extensions(tmp_path: Path) -> None:
    """collect_file_signals() returns correct extension counts from a JSONL log."""
    store = tmp_path / "store"
    log_dir = store / "history"
    log_dir.mkdir(parents=True)
    log_path = log_dir / "files_edited.jsonl"

    entries = [
        {"timestamp": _recent_ts(), "ext": ".py", "path": "/proj/main.py"},
        {"timestamp": _recent_ts(), "ext": ".py", "path": "/proj/utils.py"},
        {"timestamp": _recent_ts(), "ext": ".ts", "path": "/proj/app.ts"},
    ]
    log_path.write_text("\n".join(json.dumps(e) for e in entries), encoding="utf-8")

    signals = collect_file_signals(store)

    assert signals["extensions"].get("py", 0) == 2
    assert signals["extensions"].get("ts", 0) == 1


